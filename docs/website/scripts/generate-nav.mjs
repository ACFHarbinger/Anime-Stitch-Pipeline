#!/usr/bin/env node
// Generates src/nav.generated.ts from ../mkdocs.yml's `nav:` tree, so the
// Vue site's sidebar/search always mirrors the same source of truth mkdocs
// uses — never hand-maintained separately.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import yaml from "js-yaml";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DOCS_DIR = path.resolve(__dirname, "..", "..");
const MKDOCS_YML = path.join(DOCS_DIR, "mkdocs.yml");
const OUT_FILE = path.join(__dirname, "..", "src", "nav.generated.ts");

// mkdocs.yml uses PyYAML tags (!!python/name:..., !!python/object/apply:...)
// with dynamic suffixes for markdown_extensions config we don't care about
// here. js-yaml can't register a wildcard tag, so strip any such tag down
// to a plain quoted string before parsing instead.
const sanitizeYaml = (text) => text.replace(/!!python\/\S+/g, (m) => JSON.stringify(m));

function isExternal(target) {
  return /^https?:\/\//.test(target);
}

function slugify(mdPath) {
  // "tutorials/index.md" -> "/tutorials/index" ; "index.md" -> "/"
  const noExt = mdPath.replace(/\.md$/, "");
  if (noExt === "index") return "/";
  return "/" + noExt;
}

/** @returns {{title:string, path?:string, href?:string, kind:'md'|'notebook'|'external', children?:any[]}} */
function walk(node) {
  if (typeof node === "string") return null; // shouldn't happen at top level
  const [title, value] = Object.entries(node)[0];

  if (typeof value === "string") {
    if (isExternal(value)) {
      return { title, kind: "external", href: value };
    }
    if (value.endsWith(".ipynb")) {
      return { title, kind: "notebook", path: "/" + value.replace(/\.ipynb$/, ".ipynb"), source: value };
    }
    return { title, kind: "md", path: slugify(value), source: value };
  }

  if (Array.isArray(value)) {
    return { title, kind: "section", children: value.map(walk).filter(Boolean) };
  }

  return null;
}

function flatten(items, acc = []) {
  for (const item of items) {
    if (item.kind === "section") {
      flatten(item.children, acc);
    } else if (item.kind !== "external") {
      acc.push({ title: item.title, path: item.path, source: item.source, kind: item.kind });
    }
  }
  return acc;
}

const raw = readFileSync(MKDOCS_YML, "utf-8");
const doc = yaml.load(sanitizeYaml(raw));
const navTree = (doc.nav || []).map(walk).filter(Boolean);
const searchIndex = flatten(navTree);

const banner = "// AUTO-GENERATED by scripts/generate-nav.mjs from ../mkdocs.yml — do not edit by hand.\n";
const body =
  `export interface NavLeaf {\n` +
  `  title: string;\n` +
  `  kind: "md" | "notebook";\n` +
  `  path: string;\n` +
  `  source: string;\n` +
  `}\n` +
  `export interface NavExternal {\n` +
  `  title: string;\n` +
  `  kind: "external";\n` +
  `  href: string;\n` +
  `}\n` +
  `export interface NavSection {\n` +
  `  title: string;\n` +
  `  kind: "section";\n` +
  `  children: NavNode[];\n` +
  `}\n` +
  `export type NavNode = NavLeaf | NavExternal | NavSection;\n\n` +
  `export const navTree: NavNode[] = ${JSON.stringify(navTree, null, 2)};\n\n` +
  `export const searchIndex: { title: string; path: string; source: string; kind: "md" | "notebook" }[] = ${JSON.stringify(
    searchIndex,
    null,
    2
  )};\n`;

writeFileSync(OUT_FILE, banner + body);
console.log(`[generate-nav] wrote ${path.relative(process.cwd(), OUT_FILE)} (${searchIndex.length} pages)`);
